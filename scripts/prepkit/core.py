def rel(path: Path) -> str:
    return path.resolve().relative_to(ROOT).as_posix()


def write_text(path: Path, text: str) -> bool:
    """Write with LF endings; return True if content changed."""
    path.parent.mkdir(parents=True, exist_ok=True)
    old = path.read_text(encoding="utf-8") if path.exists() else None
    if old == text:
        return False
    with open(path, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(text)
    return True


def slugify(text: str) -> str:
    text = re.sub(r"[^a-z0-9]+", "-", text.lower())
    return text.strip("-")


# ---------------------------------------------------------------- frontmatter

FM_RE = re.compile(r"\A---\r?\n(.*?)\r?\n---\r?\n?", re.S)
GENERATED_MARK = "# --- generated by `prep build`: do not edit below this line ---"
GENERATED_KEYS = ("status", "next_review", "interval_days", "streak", "attempts")


def _norm(value):
    if isinstance(value, (dt.date, dt.datetime)):
        return value.isoformat()
    if isinstance(value, dict):
        return {k: _norm(v) for k, v in value.items()}
    if isinstance(value, list):
        return [_norm(v) for v in value]
    return value


def read_frontmatter(path: Path) -> tuple[dict, str]:
    return parse_frontmatter(path.read_text(encoding="utf-8"))


def parse_frontmatter(text: str) -> tuple[dict, str]:
    m = FM_RE.match(text)
    if not m:
        return {}, text
    meta = yaml.safe_load(m.group(1)) or {}
    return _norm(meta), text[m.end():]


_PLAIN = re.compile(r"^[A-Za-z0-9_./+()-][A-Za-z0-9 _./+()-]*$")


def _scalar(v) -> str:
    if v is None:
        return "null"
    if isinstance(v, bool):
        return "true" if v else "false"
    if isinstance(v, (int, float)):
        return repr(round(v, 1)) if isinstance(v, float) else str(v)
    s = str(v)
    if re.fullmatch(r"\d{4}-\d{2}-\d{2}", s):
        return s
    if _PLAIN.match(s) and s.lower() not in ("true", "false", "null", "yes", "no", "on", "off") \
            and not re.fullmatch(r"[\d.]+", s) and not s.endswith(" "):
        return s
    return json.dumps(s, ensure_ascii=False)


def _inline(v) -> str:
    if isinstance(v, dict):
        return "{" + ", ".join(f"{k}: {_inline(x)}" for k, x in v.items()) + "}"
    if isinstance(v, list):
        return "[" + ", ".join(_inline(x) for x in v) + "]"
    return _scalar(v)


def dump_frontmatter(meta: dict) -> str:
    lines = ["---"]
    manual = [k for k in meta if k not in GENERATED_KEYS]
    for k in manual:
        lines.append(f"{k}: {_inline(meta[k])}")
    gen = [k for k in GENERATED_KEYS if k in meta]
    if gen:
        lines.append(GENERATED_MARK)
        for k in gen:
            v = meta[k]
            if k == "attempts":
                if not v:
                    lines.append("attempts: []")
                else:
                    lines.append("attempts:")
                    lines.extend(f"  - {_inline(a)}" for a in v)
            else:
                lines.append(f"{k}: {_inline(v)}")
    lines.append("---")
    return "\n".join(lines) + "\n"


def write_entry(path: Path, meta: dict, body: str) -> bool:
    return write_text(path, dump_frontmatter(meta) + body)


def replace_block(body: str, name: str, content: str) -> str:
    """Replace text between <!-- prep:NAME:start --> and <!-- prep:NAME:end -->."""
    start, end = f"<!-- prep:{name}:start -->", f"<!-- prep:{name}:end -->"
    block = f"{start}\n{content.rstrip()}\n{end}"
    pattern = re.compile(re.escape(start) + r".*?" + re.escape(end), re.S)
    if pattern.search(body):
        return pattern.sub(lambda _: block, body)
    return body


# ---------------------------------------------------------------- items

@dataclass
class Item:
    path: Path
    meta: dict
    body: str
    attempts: list = field(default_factory=list)  # filled from attempts.csv
    srs: dict = field(default_factory=dict)        # filled by srs.schedule

    @property
    def id(self) -> str:
        return self.meta["id"]

    @property
    def type(self) -> str:
        return self.meta.get("type", "")

    @property
    def title(self) -> str:
        return self.meta.get("title", self.id)

    @property
    def difficulty(self) -> str:
        return self.meta.get("difficulty", "")

    @property
    def tags(self) -> list:
        return self.meta.get("tags") or []

    @property
    def reviewable(self) -> bool:
        return self.type in ("lc", "sd", "concept", "star")

    def target(self, cfg: dict) -> float | None:
        if self.meta.get("target_minutes"):
            return float(self.meta["target_minutes"])
        if self.type == "lc":
            return float(cfg["targets"].get(self.difficulty, 25))
        if self.type == "oa":
            return float(self.meta.get("time_limit") or 0) or None
        return cfg["type_targets"].get(self.type)

    def label(self) -> str:
        if self.type == "lc":
            return f"{self.meta.get('number', 0)}. {self.title}"
        return self.title


SKIP_DIRS = {".git", ".github", "templates", "node_modules", "__pycache__", ".venv", "assets", "data", "scripts"}


def iter_markdown(root: Path = ROOT):
    for dirpath, dirnames, filenames in os.walk(root):
        dirnames[:] = sorted(d for d in dirnames if d not in SKIP_DIRS and not d.startswith("."))
        for name in sorted(filenames):
            if name.endswith(".md"):
                yield Path(dirpath) / name


def load_items() -> dict[str, Item]:
    items: dict[str, Item] = {}
    for path in iter_markdown():
        if path.name == "README.md":
            continue
        meta, body = read_frontmatter(path)
        if not meta.get("id"):
            continue
        if meta["id"] in items:
            raise SystemExit(f"duplicate id {meta['id']}: {rel(path)} and {rel(items[meta['id']].path)}")
        items[meta["id"]] = Item(path, meta, body)
    for row in read_attempts():
        if row["id"] in items:
            items[row["id"]].attempts.append(row)
    for it in items.values():
        it.attempts.sort(key=lambda r: r["date"])
    return items


# ---------------------------------------------------------------- attempts

def read_attempts() -> list[dict]:
    if not ATTEMPTS_PATH.exists():
        return []
    with open(ATTEMPTS_PATH, encoding="utf-8", newline="") as fh:
        rows = list(csv.DictReader(fh))
    for r in rows:
        r["minutes"] = float(r["minutes"]) if r.get("minutes") else None
    return rows


def append_attempt(row: dict) -> None:
    new = not ATTEMPTS_PATH.exists()
    with open(ATTEMPTS_PATH, "a", encoding="utf-8", newline="") as fh:
        w = csv.DictWriter(fh, fieldnames=ATTEMPT_FIELDS, lineterminator="\n")
        if new:
            w.writeheader()
        out = {k: row.get(k, "") for k in ATTEMPT_FIELDS}
        if isinstance(out["minutes"], float):
            out["minutes"] = f"{out['minutes']:.1f}"
        w.writerow(out)


def rewrite_attempts(rows: list[dict]) -> None:
    with open(ATTEMPTS_PATH, "w", encoding="utf-8", newline="") as fh:
        w = csv.DictWriter(fh, fieldnames=ATTEMPT_FIELDS, lineterminator="\n")
        w.writeheader()
        for r in sorted(rows, key=lambda r: (r["date"], r["id"])):
            out = {k: r.get(k, "") for k in ATTEMPT_FIELDS}
            if isinstance(out["minutes"], float):
                out["minutes"] = f"{out['minutes']:.1f}"
            elif out["minutes"] is None:
                out["minutes"] = ""
            w.writerow(out)


def parse_phases(text: str) -> dict:
    out = {}
    for part in (text or "").split(";"):
        if "=" in part:
            k, v = part.split("=", 1)
            out[k.strip()] = float(v)
    return out


def is_timed(row: dict) -> bool:
    return row.get("minutes") is not None and row.get("source") in TIMED_SOURCES


