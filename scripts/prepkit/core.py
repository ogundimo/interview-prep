def md_link(text: str, target: Path, base: Path) -> str:
    """Relative markdown link from the folder `base` to `target`."""
    relpath = os.path.relpath(target, base).replace(os.sep, "/")
    return f"[{text}]({relpath})"


def fmt_min(m) -> str:
    if m is None:
        return "-"
    return f"{m:.0f}m" if m >= 10 else f"{m:.1f}m"
